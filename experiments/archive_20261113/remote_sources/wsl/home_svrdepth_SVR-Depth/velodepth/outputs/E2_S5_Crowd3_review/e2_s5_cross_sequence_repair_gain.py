def nested_tensors(value):
    if isinstance(value, torch.Tensor):
        yield value
    elif isinstance(value, (list, tuple)):
        for item in value:
            yield from nested_tensors(item)
    elif isinstance(value, dict):
        for item in value.values():
            yield from nested_tensors(item)


def add_nested_tensor_stats(row, prefix, value):
    tensors = [t.detach().float().reshape(-1).cpu() for t in nested_tensors(value)]
    tensors = [t for t in tensors if t.numel()]
    if not tensors:
        for suffix in ("mean", "std", "p10", "p50", "p90", "finite_ratio"):
            row[f"{prefix}_{suffix}"] = float("nan")
        return
    vals = torch.cat(tensors)
    finite = vals[torch.isfinite(vals)]
    row[f"{prefix}_finite_ratio"] = float(finite.numel() / max(vals.numel(), 1))
    if not finite.numel():
        for suffix in ("mean", "std", "p10", "p50", "p90"):
            row[f"{prefix}_{suffix}"] = float("nan")
        return
    row[f"{prefix}_mean"] = float(finite.mean().item())
    row[f"{prefix}_std"] = float(finite.std(unbiased=False).item())
    q = torch.quantile(finite, torch.tensor([0.10, 0.50, 0.90]))
    row[f"{prefix}_p10"] = float(q[0].item())
    row[f"{prefix}_p50"] = float(q[1].item())
    row[f"{prefix}_p90"] = float(q[2].item())


def feature_gap_rows_for_anchor(anchor, base_features, donor_features):
    """Return state-vs-donor feature discrepancy, globally and per quadrant."""
    out_rows = []
    for tile_id in [-1, 0, 1, 2, 3]:
        sum_diff_sq = 0.0
        sum_base_sq = 0.0
        sum_abs = 0.0
        sum_dot = 0.0
        sum_donor_sq = 0.0
        n = 0
        for base, donor in zip(base_features, donor_features):
            _, _, h, w = base.shape
            if tile_id == -1:
                y0, y1, x0, x1 = 0, h, 0, w
            else:
                y0, y1, x0, x1 = tile_bounds(h, w, tile_id)
            b = base[:, :, y0:y1, x0:x1].detach().float()
            d = donor[:, :, y0:y1, x0:x1].detach().float()
            diff = d - b
            sum_diff_sq += float(torch.sum(diff * diff).item())
            sum_base_sq += float(torch.sum(b * b).item())
            sum_donor_sq += float(torch.sum(d * d).item())
            sum_dot += float(torch.sum(b * d).item())
            sum_abs += float(torch.sum(diff.abs()).item())
            n += diff.numel()
        out_rows.append({
            "anchor_frame": anchor,
            "tile_id": tile_id,
            "tile_name": "full" if tile_id == -1 else TILES[tile_id],
            "feature_gap_mean_abs": sum_abs / max(n, 1),
            "feature_gap_rel_l2": (sum_diff_sq ** 0.5) / max(sum_base_sq ** 0.5, 1e-12),
            "feature_cosine_similarity": sum_dot / max((sum_base_sq * sum_donor_sq) ** 0.5, 1e-12),
        })
    return out_rows


def make_state_observable_row(anchor, state):
    row = {
        "anchor_frame": anchor,
        "current_t": getattr(state, "current_t", float("nan")),
        "distance_kf": getattr(state, "distance_kf", float("nan")),
        "flow_magnitude": getattr(state, "flow_magnitude", float("nan")),
        "total_luma_change": getattr(state, "total_luma_change", float("nan")),
        "first_keyframe": getattr(state, "first_keyframe", None),
    }
    for field in ("radius_teacher", "confidence_teacher", "fast_tail_radius", "fast_tail_confidence"):
        add_nested_tensor_stats(row, field, getattr(state, field, None))
    return row


def build_gain_audit(current_rows, summary_rows, state_rows, feature_rows):
    state_by_anchor = {int(r["anchor_frame"]): r for r in state_rows}
    gap_by_key = {(int(r["anchor_frame"]), int(r["tile_id"])): r for r in feature_rows}
    current_lookup = {(int(r["anchor_frame"]), r["branch"]): r for r in current_rows}
    pairs = []
    for summ in summary_rows:
        anchor = int(summ["anchor_frame"])
        horizon = int(summ["horizon_H"])
        base = current_lookup.get((anchor, "PROP_FAST_READOUT"))
        if not base:
            continue
        for tile_id in (0, 1, 2, 3, -1):
            if tile_id == -1:
                branch = "FULL_FEATURE_COMMIT"
                current_branch = "FULL_DONOR_FAST"
            else:
                branch = f"TILE_{tile_id}_FEATURE_COMMIT"
                current_branch = f"TILE_{tile_id}_HYBRID_OUTPUT"
            cur = current_lookup.get((anchor, current_branch))
            if not cur:
                continue
            def fnum(row, key):
                try:
                    return float(row[key])
                except (KeyError, TypeError, ValueError):
                    return float("nan")
            gain_absrel = fnum(summ, f"G_absrel_OUTPUT_ONLY_vs_{branch}")
            gain_rmse = fnum(summ, f"G_rmse_OUTPUT_ONLY_vs_{branch}")
            gain_delta1 = fnum(summ, f"G_delta1_OUTPUT_ONLY_vs_{branch}")
            row = {
                "anchor_frame": anchor,
                "horizon_H": horizon,
                "tile_id": tile_id,
                "branch": branch,
                "current_gain_absrel": fnum(base, "absrel") - fnum(cur, "absrel"),
                "current_gain_rmse": fnum(base, "rmse") - fnum(cur, "rmse"),
                "current_gain_delta1": fnum(cur, "delta1") - fnum(base, "delta1"),
                "future_gain_absrel": gain_absrel,
                "future_gain_rmse": gain_rmse,
                "future_gain_delta1": gain_delta1,
                "paired_future_frames": summ.get(f"paired_frames_{branch}_absrel", ""),
            }
            row.update({f"state_{k}": v for k, v in state_by_anchor.get(anchor, {}).items() if k != "anchor_frame"})
            gap = gap_by_key.get((anchor, tile_id), {})
            row.update({k: v for k, v in gap.items() if k not in ("anchor_frame", "tile_id", "tile_name")})
            pairs.append(row)
    summaries = []
    groups = {}
    for row in pairs:
        groups.setdefault((row["branch"], int(row["horizon_H"])), []).append(row)
    for (branch, horizon), rows in sorted(groups.items()):
        def finite_vals(key):
            vals = [float(r[key]) for r in rows if math.isfinite(float(r[key]))]
            return vals
        abs_g = finite_vals("future_gain_absrel")
        cur_g = finite_vals("current_gain_absrel")
        summaries.append({
            "branch": branch,
            "horizon_H": horizon,
            "n_anchor_rows": len(rows),
            "mean_current_gain_absrel": sum(cur_g)/len(cur_g) if cur_g else float("nan"),
            "mean_future_gain_absrel": sum(abs_g)/len(abs_g) if abs_g else float("nan"),
            "median_future_gain_absrel": float(np.median(abs_g)) if abs_g else float("nan"),
            "anchors_with_positive_future_absrel_gain": sum(v > 0 for v in abs_g),
            "anchors_with_negative_future_absrel_gain": sum(v < 0 for v in abs_g),
            "current_future_absrel_sign_agreement": sum((float(r["current_gain_absrel"]) > 0) == (float(r["future_gain_absrel"]) > 0) for r in rows if math.isfinite(float(r["current_gain_absrel"])) and math.isfinite(float(r["future_gain_absrel"]))),
            "note": "descriptive only; small number of anchors, not a trained predictor or statistical generalization claim",
        })
    return pairs, summaries


def main():
    ap = argparse.ArgumentParser(description="E2-S5 state-conditioned repair-gain audit")
    ap.add_argument("--data-root", default="/root/autodl-tmp/datasets/rgbd_bonn_crowd2")
    ap.add_argument("--frames", type=int, default=46)
    ap.add_argument("--anchors", default="9,37", help="zero-based development anchors")
    ap.add_argument("--horizons", default="1,4,8")
    ap.add_argument("--tiles", default="0,1,2,3", help="quadrants: 0=TL,1=TR,2=BL,3=BR")
    ap.add_argument("--max-time-diff", type=float, default=0.02)
    ap.add_argument("--gt-scale", type=float, default=5000.0)
    ap.add_argument("--resolution-level", type=int, default=0)
    ap.add_argument("--tolerance", type=float, default=1e-6)
    ap.add_argument("--out-dir", default="outputs/e2_s5_state_conditioned_repair/crowd2_multi_anchor_run01")
    args = ap.parse_args()

    anchors = mh.parse_ints(args.anchors, "--anchors", 1)
    horizons = mh.parse_ints(args.horizons, "--horizons", 1)
    try:
        tiles = sorted(set(int(x.strip()) for x in args.tiles.split(",") if x.strip()))
    except ValueError:
        ap.error("--tiles must be comma-separated integers selected from 0,1,2,3")
    if not tiles or any(t not in TILES for t in tiles):
        ap.error("--tiles values must be selected from 0,1,2,3")
    if len(set(tiles)) != len(tiles):
        ap.error("--tiles cannot contain duplicates")
    if args.frames < max(anchors)+max(horizons)+1:
        ap.error(f"--frames must include anchor {max(anchors)} plus horizon {max(horizons)}")
    if not torch.cuda.is_available():
        raise RuntimeError("GPU required. Run E2-S3 on the GPU instance, not no-card mode.")

    out_dir = Path(args.out_dir)
    if out_dir.exists() and any(out_dir.iterdir()):
        raise FileExistsError(f"Output directory is not empty: {out_dir}; choose a new --out-dir")
    out_dir.mkdir(parents=True, exist_ok=True)

    torch.set_grad_enabled(False)
    torch.backends.cudnn.benchmark = False
    root = Path(args.data_root)
    rgb_rows = mh.read_index(root, "rgb.txt", "rgb")
    depth_rows = mh.read_index(root, "depth.txt", "depth")
    selected = rgb_rows[:args.frames]
    if len(selected) != args.frames:
        raise RuntimeError(f"Requested {args.frames} RGB frames, found {len(selected)}")
    records = mh.match_gt(selected, depth_rows, args.max_time_diff)
    gt = [mh.load_gt(row["gt_path"], args.gt_scale) if row["gt_available"] else None for row in records]

    print("=== E2-S5 state-conditioned repair-gain audit ===")
    print(f"Frames={args.frames}; anchors={anchors}; horizons={horizons}; tiles={tiles}")
    print(f"GT matched={sum(bool(r['gt_available']) for r in records)}/{len(records)}; tolerance={args.tolerance}")
    print("Weights frozen. Full-frame donor encoder remains active; this is not a compute-saving benchmark.")

    frames = mh.load_frames(records)
    raw_h, raw_w = int(frames.shape[-2]), int(frames.shape[-1])
    model = VeloDepth.from_pretrained("lpiccinelli/velodepth")
    model.to(torch.device("cuda"))
    model.eval()
    model.resolution_level = args.resolution_level
    model.interpolation_mode = "bilinear"
    inputs, metas = mh.capture_inputs(model, frames)
    total_frames = int(metas[0]["T"])
    paddings, padded_shape = get_paddings((raw_h, raw_w), model.shape_constraints["ratio_bounds"])
    stream = VeloDepthStream(model)
    initial_snapshot = capture_state(model, StreamState())

    current_rows, future_rows, noop_rows, geometry_rows = [], [], [], []
    status_rows, timing_rows, summary_rows = [], [], []
    state_observable_rows, feature_gap_rows = [], []

    for anchor in anchors:
        print(f"\n--- anchor A{anchor} ---")
        state_before = mh.prefix_state(model, stream, inputs, total_frames, anchor, initial_snapshot)
        pre_anchor_snapshot = capture_state(model, state_before)
        prop_state = clone_state(state_before)
        restore_state(model, prop_state, pre_anchor_snapshot)
        with torch.inference_mode():
            prop_out, prop_state, restart_anchor = stream.propagate_step(inputs, anchor, prop_state, total_frames)
        if restart_anchor:
            status_rows.append({"anchor_frame": anchor, "status": "skipped_anchor_restart",
                                "reason": "native propagation requested restart at anchor"})
            print(f"SKIP A{anchor}: propagation requests restart at anchor")
            continue
        post_prop_runtime = capture_state(model, prop_state)
        baseline_state = clone_state(prop_state)

        torch.cuda.synchronize()
        t0 = time.perf_counter()
        with torch.inference_mode():
            donor_features = build_teacher_conditioned_features(
                model, inputs, stream, anchor, total_frames, prop_state.rays_base)
        torch.cuda.synchronize()
        donor_generation_ms = (time.perf_counter()-t0)*1000.0

        if len(baseline_state.features_teacher) != len(donor_features):
            raise RuntimeError(f"A{anchor}: donor/base feature level count mismatch")
        for level, (base, donor) in enumerate(zip(baseline_state.features_teacher, donor_features)):
            if tuple(base.shape) != tuple(donor.shape):
                raise RuntimeError(f"A{anchor}: feature shape mismatch at level {level}: {tuple(base.shape)} vs {tuple(donor.shape)}")

        # E2-S5: observable propagation-state diagnostics and feature discrepancy.
        state_observable_rows.append(make_state_observable_row(anchor, baseline_state))
        feature_gap_rows.extend(feature_gap_rows_for_anchor(
            anchor, baseline_state.features_teacher, donor_features))

        # Current-frame references. Keep the decoder in this fast-readout context
        # until all hybrid readouts have been computed; native keyframe refresh can
        # mutate runtime shape/cache attributes.
        torch.cuda.synchronize()
        t0 = time.perf_counter()
        with torch.inference_mode():
            prop_radius, prop_conf = model.pixel_decoder.readout_fast_features(baseline_state.features_teacher)
        torch.cuda.synchronize()
        prop_fast_readout_ms = (time.perf_counter()-t0)*1000.0
        torch.cuda.synchronize()
        t0 = time.perf_counter()
        with torch.inference_mode():
            full_radius, full_conf = model.pixel_decoder.readout_fast_features(donor_features)
        torch.cuda.synchronize()
        full_donor_readout_ms = (time.perf_counter()-t0)*1000.0
        prop_out_ref = StepOutput(radius=prop_radius, rays=prop_out.rays.detach().clone(),
                                  confidence=prop_conf, kind="prop_reference", frame=anchor)
        full_out = StepOutput(radius=full_radius, rays=prop_out.rays.detach().clone(),
                              confidence=full_conf, kind="full_donor_fast", frame=anchor)

        for name, out in (("PROP", prop_out), ("PROP_FAST_READOUT", prop_out_ref),
                          ("FULL_DONOR_FAST", full_out)):
            current_rows.append(metrics_row(anchor, anchor, name, out, model, paddings, padded_shape, gt[anchor], records))
            save_prediction(out_dir, anchor, anchor, name, out, model, paddings, padded_shape, gt[anchor])

        # Generate per-quadrant hybrid features and the corresponding current outputs.
        hybrid_by_tile = {}
        tile_readout_ms = {}
        for tile_id in tiles:
            t0 = time.perf_counter()
            hybrid = make_tile_hybrid(baseline_state.features_teacher, donor_features, tile_id, anchor, geometry_rows)
            with torch.inference_mode():
                radius, confidence = model.pixel_decoder.readout_fast_features(hybrid)
            torch.cuda.synchronize()
            tile_readout_ms[tile_id] = (time.perf_counter()-t0)*1000.0
            hybrid_by_tile[tile_id] = hybrid
            tile_out = StepOutput(radius=radius, rays=prop_out.rays.detach().clone(),
                                  confidence=confidence, kind=f"tile_{tile_id}_hybrid", frame=anchor)
            branch_name = f"TILE_{tile_id}_HYBRID_OUTPUT"
            current_rows.append(metrics_row(anchor, anchor, branch_name, tile_out, model,
                                            paddings, padded_shape, gt[anchor], records))
            save_prediction(out_dir, anchor, anchor, branch_name, tile_out, model,
                            paddings, padded_shape, gt[anchor])

        # Native full refresh is a separate current-frame reference, not a paired state trajectory.
        # Run it after all fast readouts to avoid leaking keyframe runtime changes into them.
        native_state = clone_state(state_before)
        restore_state(model, native_state, pre_anchor_snapshot)
        with torch.inference_mode():
            native_out, native_state = stream.keyframe_step(inputs, anchor, native_state, total_frames)
        current_rows.append(metrics_row(anchor, anchor, "NATIVE_FULL_REFRESH", native_out,
                                        model, paddings, padded_shape, gt[anchor], records))
        save_prediction(out_dir, anchor, anchor, "NATIVE_FULL_REFRESH", native_out,
                        model, paddings, padded_shape, gt[anchor])

        # Each future branch starts from the same native propagated state at the anchor.
        branch_names = ["OUTPUT_ONLY", "NOOP_COMMIT"] + [f"TILE_{t}_FEATURE_COMMIT" for t in tiles] + ["FULL_FEATURE_COMMIT"]
        branch_states = {name: clone_state(baseline_state) for name in branch_names}
        assign_noop(branch_states["NOOP_COMMIT"], baseline_state)
        for tile_id in tiles:
            hybrid = hybrid_by_tile[tile_id]
            branch_states[f"TILE_{tile_id}_FEATURE_COMMIT"].features_teacher = clone_value(hybrid)
            branch_states[f"TILE_{tile_id}_FEATURE_COMMIT"].fast_tail_features = clone_value(hybrid)
        branch_states["FULL_FEATURE_COMMIT"].features_teacher = clone_value(donor_features)
        branch_states["FULL_FEATURE_COMMIT"].fast_tail_features = clone_value(donor_features)

        noop_anchor_state_diff = max_state_diff(branch_states["NOOP_COMMIT"], baseline_state)
        if noop_anchor_state_diff > args.tolerance:
            raise AssertionError(f"A{anchor}: NOOP state changed at anchor: {noop_anchor_state_diff}")

        anchor_rows = []
        max_noop_output_diff = 0.0
        max_noop_state_diff = 0.0
        noop_pass = True
        for step in range(1, max(horizons)+1):
            frame_idx = anchor+step
            outs, restarts = {}, {}
            for branch in branch_names:
                state = branch_states[branch]
                out, state, restart = forced_propagation_step(
                    stream, inputs, frame_idx, state, total_frames, post_prop_runtime, model)
                if branch != "OUTPUT_ONLY":
                    sync_scheduler(state, branch_states["OUTPUT_ONLY"])
                branch_states[branch] = state
                outs[branch], restarts[branch] = out, restart

            out_diff = max_output_diff(outs["OUTPUT_ONLY"], outs["NOOP_COMMIT"])
            state_diff = max_state_diff(branch_states["OUTPUT_ONLY"], branch_states["NOOP_COMMIT"])
            restart_match = restarts["OUTPUT_ONLY"] == restarts["NOOP_COMMIT"]
            step_pass = out_diff <= args.tolerance and state_diff <= args.tolerance and restart_match
            noop_pass = noop_pass and step_pass
            max_noop_output_diff = max(max_noop_output_diff, out_diff)
            max_noop_state_diff = max(max_noop_state_diff, state_diff)
            noop_rows.append({"anchor_frame": anchor, "future_frame": frame_idx,
                              "step_from_anchor": step, "output_max_abs_diff": out_diff,
                              "state_max_abs_diff": state_diff, "restart_match": restart_match,
                              "pass_at_tolerance": step_pass, "tolerance": args.tolerance})

            for branch in branch_names:
                row = metrics_row(anchor, frame_idx, branch, outs[branch], model,
                                  paddings, padded_shape, gt[frame_idx], records)
                row["restart_requested"] = restarts[branch]
                row["scheduler_synced_to_output_only"] = branch != "OUTPUT_ONLY"
                future_rows.append(row)
                anchor_rows.append(row)
                if step in set(horizons):
                    save_prediction(out_dir, anchor, frame_idx, branch, outs[branch],
                                    model, paddings, padded_shape, gt[frame_idx])
            print(f"A{anchor} H={step}: NOOP output={out_diff:.3g}, state={state_diff:.3g}, pass={step_pass}")

        timing_rows.append({"anchor_frame": anchor, "full_frame_donor_generation_ms": donor_generation_ms,
                            "prop_fast_readout_ms": prop_fast_readout_ms,
                            "full_donor_fast_readout_ms": full_donor_readout_ms,
                            **{f"tile_{t}_hybrid_build_plus_readout_ms": tile_readout_ms[t] for t in tiles},
                            "noop_max_future_output_abs_diff": max_noop_output_diff,
                            "noop_max_future_state_abs_diff": max_noop_state_diff,
                            "noop_pass": noop_pass, "tolerance": args.tolerance})
        status_rows.append({"anchor_frame": anchor, "status": "completed", "noop_pass": noop_pass,
                            "noop_max_output_diff": max_noop_output_diff,
                            "noop_max_state_diff": max_noop_state_diff})

        for horizon in horizons:
            row = {"anchor_frame": anchor, "horizon_H": horizon,
                   "future_frames_with_gt": sum(bool(records[anchor+k]["gt_available"]) for k in range(1, horizon+1)),
                   "noop_pass": noop_pass, "noop_max_output_abs_diff": max_noop_output_diff,
                   "noop_max_state_abs_diff": max_noop_state_diff}
            for branch in branch_names:
                for key in ("absrel", "rmse", "delta1"):
                    row[f"{branch}_mean_{key}"] = mean_metric(anchor_rows, branch, key, horizon)
            for branch in [f"TILE_{t}_FEATURE_COMMIT" for t in tiles] + ["FULL_FEATURE_COMMIT", "NOOP_COMMIT"]:
                for key, higher in (("absrel", False), ("rmse", False), ("delta1", True)):
                    gain, n = paired_gain(anchor_rows, branch, key, horizon, higher_is_better=higher)
                    row[f"G_{key}_OUTPUT_ONLY_vs_{branch}"] = gain
                    row[f"paired_frames_{branch}_{key}"] = n
            summary_rows.append(row)

        print(f"A{anchor}: NOOP pass={noop_pass}; full donor={donor_generation_ms:.2f}ms; "
              + ", ".join(f"tile{t} readout={tile_readout_ms[t]:.2f}ms" for t in tiles))

    write_csv(out_dir/"e2_s3_current_metrics.csv", current_rows)
    write_csv(out_dir/"e2_s3_future_metrics.csv", future_rows)
    write_csv(out_dir/"e2_s3_noop_audit.csv", noop_rows)
    write_csv(out_dir/"e2_s3_tile_geometry.csv", geometry_rows)
    write_csv(out_dir/"e2_s3_horizon_summary.csv", summary_rows)
    write_csv(out_dir/"e2_s3_anchor_status.csv", status_rows)
    write_csv(out_dir/"e2_s3_timing.csv", timing_rows)

    gain_pairs, branch_gain_summary = build_gain_audit(
        current_rows, summary_rows, state_observable_rows, feature_gap_rows)
    write_csv(out_dir/"e2_s5_anchor_state_observables.csv", state_observable_rows)
    write_csv(out_dir/"e2_s5_feature_gap_by_tile.csv", feature_gap_rows)
    write_csv(out_dir/"e2_s5_current_future_gain_pairs.csv", gain_pairs)
    write_csv(out_dir/"e2_s5_branch_gain_summary.csv", branch_gain_summary)

    metadata = {
        "experiment": "E2-S5_state_conditioned_repair_gain_audit",
        "model": "lpiccinelli/velodepth",
        "weights_frozen": True,
        "data_root": str(root), "frames": args.frames,
        "anchors_zero_based": anchors, "horizons": horizons, "tiles": {str(t): TILES[t] for t in tiles},
        "gt_match_tolerance_seconds": args.max_time_diff, "gt_scale": args.gt_scale,
        "resolution_level": args.resolution_level, "noop_tolerance": args.tolerance,
        "tile_operation": "per feature level, replace exactly one normalized quadrant of BCHW features_teacher with teacher-conditioned donor; commit features_teacher and fast_tail_features only",
        "control": "OUTPUT_ONLY starts from native propagated state; same anchor current-output candidate is evaluated separately for each tile in current_metrics; future trajectory has no persistent donor commit",
        "future_policy": "forced propagation; restart requests recorded but ignored; scheduler fields synchronized to OUTPUT_ONLY",
        "state_cache_fields_committed": ["features_teacher", "fast_tail_features"],
        "state_fields_held_native": ["radius_teacher", "confidence_teacher", "fast_tail_radius", "fast_tail_confidence", "rays_base"],
        "limitations": [
            "A9 and A37 are development anchors, not independent validation",
            "full-frame teacher encoder is still run; this experiment tests spatial locality, not compute savings",
            "feature maps are hard-spliced without a halo or learned boundary adapter",
            "future forced propagation does not estimate online policy behavior with executed keyframe restarts",
            "no training is performed",
        ],
        "e2_s5_method": "log observable propagation-state scalars and radius/confidence distributions; compute per-tile propagated-vs-donor feature discrepancy; pair anchor current-frame oracle gains with forced-propagation future GT gains",
        "e2_s5_warning": "descriptive diagnostic only; anchors from one sequence are not independent validation and no predictor is trained",
        "outputs": {"e2_s5_anchor_state_observables": str(out_dir/"e2_s5_anchor_state_observables.csv"),
                    "e2_s5_feature_gap_by_tile": str(out_dir/"e2_s5_feature_gap_by_tile.csv"),
                    "e2_s5_current_future_gain_pairs": str(out_dir/"e2_s5_current_future_gain_pairs.csv"),
                    "e2_s5_branch_gain_summary": str(out_dir/"e2_s5_branch_gain_summary.csv"),
                    "current_metrics": str(out_dir/"e2_s3_current_metrics.csv"),
                    "future_metrics": str(out_dir/"e2_s3_future_metrics.csv"),
                    "noop_audit": str(out_dir/"e2_s3_noop_audit.csv"),
                    "tile_geometry": str(out_dir/"e2_s3_tile_geometry.csv"),
                    "horizon_summary": str(out_dir/"e2_s3_horizon_summary.csv"),
                    "anchor_status": str(out_dir/"e2_s3_anchor_status.csv"),
                    "timing": str(out_dir/"e2_s3_timing.csv"),
                    "predictions": str(out_dir/"predictions")},
    }
    (out_dir/"e2_s3_metadata.json").write_text(json.dumps(metadata, ensure_ascii=False, indent=2), encoding="utf-8")
    print("\n=== E2-S5 finished ===")
    print("Current metrics:", out_dir/"e2_s3_current_metrics.csv")
    print("Future metrics:", out_dir/"e2_s3_future_metrics.csv")
    print("NOOP audit:", out_dir/"e2_s3_noop_audit.csv")
    print("Tile geometry:", out_dir/"e2_s3_tile_geometry.csv")
    print("Horizon summary:", out_dir/"e2_s3_horizon_summary.csv")
    print("E2-S5 state observables:", out_dir/"e2_s5_anchor_state_observables.csv")
    print("E2-S5 feature gaps:", out_dir/"e2_s5_feature_gap_by_tile.csv")
    print("E2-S5 current/future gains:", out_dir/"e2_s5_current_future_gain_pairs.csv")
    print("E2-S5 branch summary:", out_dir/"e2_s5_branch_gain_summary.csv")
    print("Positive G_absrel means the tile/full commit reduced future AbsRel versus OUTPUT_ONLY.")
    print("Do not claim compute savings: full-frame teacher encoding is still used.")


