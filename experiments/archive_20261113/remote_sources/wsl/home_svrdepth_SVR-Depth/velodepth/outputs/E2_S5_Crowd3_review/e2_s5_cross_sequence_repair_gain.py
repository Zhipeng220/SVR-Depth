def build_teacher_conditioned_features(model, inputs, stream, frame_idx, total_frames, rays_base):
    """Generate full-frame teacher-conditioned features in the anchor ray field."""
    image = stream._frame(inputs["image"], frame_idx, total_frames)
    features, tokens = model.pixel_encoder(image)
    features = [model.stacking_fn(features[i:j]).contiguous()
                for i, j in model.slices_encoder_range]
    tokens = [model.stacking_fn(tokens[i:j]).contiguous()
              for i, j in model.slices_encoder_range]
    metas = [{"T": 1, "B": 1}]
    base_inputs = {"image": image, "features": features, "tokens": tokens}
    model.pixel_decoder.set_shapes(base_inputs, metas)
    adapted_features = model.pixel_decoder.input_adapter(features)
    radial = model.pixel_decoder.radial_module
    ray_embedding = radial.embed_rays(rays_base)
    conditioned = radial.condition(adapted_features, ray_embedding)
    h_common, w_common = radial.shapes
    return [x.reshape(x.shape[0], h_common, w_common, x.shape[-1])
             .permute(0, 3, 1, 2).contiguous() for x in conditioned]


def tile_bounds(h, w, tile_id):
    hm, wm = (h + 1) // 2, (w + 1) // 2
    if tile_id == 0:
        return 0, hm, 0, wm
    if tile_id == 1:
        return 0, hm, wm, w
    if tile_id == 2:
        return hm, h, 0, wm
    if tile_id == 3:
        return hm, h, wm, w
    raise ValueError(f"tile_id must be 0..3, got {tile_id}")


def make_tile_hybrid(base_features, donor_features, tile_id, anchor, geometry_rows):
    if len(base_features) != len(donor_features):
        raise RuntimeError(f"A{anchor}: feature-level count mismatch")
    hybrid = []
    for level, (base, donor) in enumerate(zip(base_features, donor_features)):
        if not isinstance(base, torch.Tensor) or not isinstance(donor, torch.Tensor):
            raise TypeError(f"A{anchor}: level {level} is not a tensor")
        if tuple(base.shape) != tuple(donor.shape):
            raise RuntimeError(
                f"A{anchor}: level {level} shape mismatch {tuple(base.shape)} vs {tuple(donor.shape)}"
            )
        if base.ndim != 4:
            raise RuntimeError(f"A{anchor}: expected BCHW feature at level {level}, got {tuple(base.shape)}")
        _, _, h, w = base.shape
        y0, y1, x0, x1 = tile_bounds(h, w, tile_id)
        mixed = base.detach().clone()
        mixed[:, :, y0:y1, x0:x1] = donor[:, :, y0:y1, x0:x1]
        hybrid.append(mixed.contiguous())
        geometry_rows.append({
            "anchor_frame": anchor,
            "tile_id": tile_id,
            "tile_name": TILES[tile_id],
            "feature_level": level,
            "height": h,
            "width": w,
            "y0": y0,
            "y1_exclusive": y1,
            "x0": x0,
            "x1_exclusive": x1,
            "tile_cells": (y1-y0)*(x1-x0),
            "all_cells": h*w,
            "tile_area_fraction": ((y1-y0)*(x1-x0))/(h*w),
            "channels": int(base.shape[1]),
        })
    return hybrid


def metrics_row(anchor, frame_idx, branch, out, model, paddings, padded_shape, gt, records):
    m = mh.eval_output(out, model, paddings, padded_shape, gt)
    dt = records[frame_idx]["time_diff"]
    return {
        "anchor_frame": anchor,
        "frame_index": frame_idx,
        "step_from_anchor": frame_idx-anchor,
        "branch": branch,
        "rgb_timestamp": records[frame_idx]["rgb_ts"],
        "gt_available": bool(records[frame_idx]["gt_available"]),
        "gt_time_diff_ms": dt*1000.0 if math.isfinite(dt) else float("nan"),
        "absrel": m["absrel"],
        "rmse": m["rmse"],
        "delta1": m["delta1"],
        "valid_ratio": m["valid_ratio"],
    }


def save_prediction(out_dir, anchor, frame_idx, branch, out, model, paddings, padded_shape, gt):
    if gt is None:
        return
    pred = mh.output_depth(out, model, paddings, padded_shape).astype(np.float32)
    valid = np.isfinite(gt) & (gt > 0) & np.isfinite(pred) & (pred > 0)
    path = Path(out_dir)/"predictions"/f"a{anchor:03d}_f{frame_idx:03d}_{branch}.npz"
    path.parent.mkdir(parents=True, exist_ok=True)
    np.savez_compressed(path, pred=pred, gt=gt.astype(np.float32), valid=valid)


def forced_propagation_step(stream, inputs, frame_idx, state, total_frames, runtime_snapshot, model):
    restore_runtime(model, runtime_snapshot)
    out, state, restart = stream.propagate_step(inputs, frame_idx, state, total_frames)
    if restart:
        state.first_keyframe = False
        state.distance_kf += 1
        state.current_t = frame_idx+1
    return out, state, bool(restart)


def mean_metric(rows, branch, key, max_step):
    vals = [float(r[key]) for r in rows
            if r["branch"] == branch and 1 <= int(r["step_from_anchor"]) <= max_step
            and math.isfinite(float(r[key]))]
    return sum(vals)/len(vals) if vals else float("nan")


def paired_gain(rows, branch, key, max_step, higher_is_better=False):
    refs = {int(r["frame_index"]): r for r in rows
            if r["branch"] == "OUTPUT_ONLY" and 1 <= int(r["step_from_anchor"]) <= max_step}
    vals_by_frame = {int(r["frame_index"]): r for r in rows
                     if r["branch"] == branch and 1 <= int(r["step_from_anchor"]) <= max_step}
    vals = []
    for frame in sorted(set(refs) & set(vals_by_frame)):
        a, b = float(refs[frame][key]), float(vals_by_frame[frame][key])
        if math.isfinite(a) and math.isfinite(b):
            vals.append((b-a) if higher_is_better else (a-b))
    return (sum(vals)/len(vals), len(vals)) if vals else (float("nan"), 0)


