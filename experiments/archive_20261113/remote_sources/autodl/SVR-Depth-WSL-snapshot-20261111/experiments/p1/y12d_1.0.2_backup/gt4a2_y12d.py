"""Y12-D: paired skip/C*/same-ray teacher-feature recovery-space diagnostic."""
from y12d_common import *
from types import SimpleNamespace
from pathlib import Path
import argparse, fcntl, hashlib, os, sys, time, traceback, zipfile

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
INSTALLED = ("gt4a2_y12d.py", "y12d_common.py", "y12d_eval.py", "test_y12d.py", "y12d_identity.json", "y12d_SHA256SUMS")


def _manifest_records(path):
    records = {}
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        parts = line.split(maxsplit=1)
        require(len(parts) == 2, "Malformed SHA manifest: " + str(path))
        digest, rel = parts[0], parts[1].strip()
        require(len(digest) == 64 and rel not in records, "Invalid/duplicate SHA manifest entry: " + rel)
        records[rel] = digest
    return records


def _verify_y05r_install(root):
    manifest = root / "experiments/p1/y05r_SHA256SUMS"
    require(manifest.is_file(), "Y05-R installed SHA manifest missing; install Y05-R 1.0.1 first")
    records = _manifest_records(manifest)
    require(len(records) == 7, "Unexpected Y05-R installed manifest shape")
    for rel, expected in records.items():
        path = root / rel
        require(path.is_file() and sha(path) == expected, "Y05-R installed source differs from reviewed 1.0.1: " + str(path))
    run = root / "run_y05r.sh"
    require(run.is_file(), "run_y05r.sh missing")
    return {str((root / rel).resolve()): digest for rel, digest in records.items()} | {str(run.resolve()): sha(run)}


def _verify_named_hashes(root, source_map, names):
    out = {}
    for name in names:
        matches = [(p, d) for p, d in source_map.items() if Path(p).name == name]
        require(len(matches) == 1, f"Expected exactly one pinned source hash for {name}, found {len(matches)}")
        path, digest = matches[0]
        p = Path(path)
        require(p.is_file() and sha(p) == digest, "Pinned source changed: " + str(p))
        out[str(p.resolve())] = digest
    return out


def _parent_paths(y05r_dir, cases):
    result = {}
    for seq in SEQS:
        wanted = sorted({int(c["snapshot_index"]) for c in cases if c["sequence"] == seq})
        directory = Path(y05r_dir) / "evaluation" / "own_parents" / "C_star" / seq
        meta_path, state_path = directory / "complete.json", directory / "parents.pt"
        require(meta_path.is_file() and state_path.is_file(),
                f"Missing C* own-history parent cache for {seq}: {directory}; keep the full Y05-R output directory, not only y05r_review.zip")
        meta = jread(meta_path)
        require(meta.get("arm") == "C_star" and meta.get("sequence") == seq,
                f"Wrong parent cache identity for {seq}")
        require(meta.get("indices") == wanted, f"C* parent snapshot indices differ for {seq}")
        require(meta.get("parent_sha256") == sha(state_path), f"C* parent cache SHA mismatch for {seq}")
        result[seq] = {"directory": str(directory.resolve()), "complete_json": str(meta_path.resolve()),
                       "complete_sha256": sha(meta_path), "parents_pt": str(state_path.resolve()),
                       "parents_sha256": sha(state_path), "indices": wanted,
                       "head_sha256": meta.get("head_sha256"), "signature": meta.get("signature")}
    return result


def prepare(args, out_dir):
    y05r_dir = find_y05r_dir(args.y05r_dir, ROOT)
    y05r_protocol, y05r_summary, y05r_signature, all_cases = validate_y05r_summary(y05r_dir)
    cases = select_cases(all_cases, args.smoke_only)
    y05r_source_hashes = _verify_y05r_install(ROOT)
    y05r_identity = jread(ROOT / "experiments/p1/y05r_identity.json")
    require(y05r_identity.get("source_protocol_sha256") == y05r_protocol.get("source_y05_signature"),
            "Installed Y05-R identity does not match the formal Y05-R protocol")

    # The C* own-history parents and final head are generated by the completed Y05-R run.
    torch = None
    import y05_common as old
    old_args = SimpleNamespace(**y05r_protocol["paths"], smoke_only=False)
    old_ctx = old.preflight(old_args)
    old_y05_dir = Path(y05r_protocol["paths"]["y05_dir"])
    old_protocol_path = old_y05_dir / "protocol.json"
    old_protocol = jread(old_protocol_path)
    require(old_ctx.plan == old_protocol, "Original Y05 preflight no longer reproduces the pinned protocol")
    require(y05r_protocol.get("source_y05_signature") == sha(old_protocol_path),
            "Y05-R source Y05 protocol signature mismatch")
    require(old_ctx.rt.torch.cuda.is_available(), "Y12-D requires the original CUDA environment")
    torch = old_ctx.rt.torch

    cstar_path = y05r_dir / "training" / "C_star" / "final.pt"
    require(cstar_path.is_file(), "Y05-R C_star/final.pt missing")
    checkpoint = torch.load(cstar_path, map_location="cpu", weights_only=False)
    require(checkpoint.get("signature") == y05r_signature and checkpoint.get("experiment") == "Y05-R"
            and checkpoint.get("kind") == "C_star", "C* checkpoint protocol identity mismatch")
    cstar_state = checkpoint.get("state")
    require(isinstance(cstar_state, dict), "C* checkpoint has no state_dict")
    cstar_head_sha = old_ctx.rt.exp1.state_sha256(cstar_state)
    require(cstar_head_sha == checkpoint.get("head_sha256"), "C* checkpoint tensor SHA mismatch")
    require(y05r_summary.get("final_checkpoints", {}).get("C_star") in (None, str(cstar_path), str(cstar_path.resolve())),
            "Y05-R summary points to a different C* checkpoint")

    parents = _parent_paths(y05r_dir, all_cases)
    for seq, meta in parents.items():
        require(meta["signature"] == y05r_signature, f"C* own-history parent signature mismatch: {seq}")
        require(meta["head_sha256"] == cstar_head_sha, f"C* own-history parent head mismatch: {seq}")

    # Pin the reviewed Y05-R files and the original Y05/runtime/model sources that produced the state.
    y05r_hashes = _verify_named_hashes(ROOT, y05r_protocol["input_sha256"],
        ("gt4a2_y05r.py", "y05r_common.py", "y05r_train.py", "y05r_eval.py", "test_y05r.py", "y05r_identity.json", "y05r_SHA256SUMS", "run_y05r.sh"))
    old_hashes = _verify_named_hashes(ROOT, old_protocol["input_sha256"],
        ("y05_common.py", "y05_engine.py", "y05_train.py", "y05_eval.py", "gt4a2_y05_future_utility.py",
         "gt4a2_y04a_native_pre_readout_eval.py", "velodepth.py", "encoder_velo.py", "decoder_velo.py"))
    critical = dict(old_ctx.plan["input_sha256"])
    critical.update({
        str((y05r_dir / "protocol.json").resolve()): sha(y05r_dir / "protocol.json"),
        str((y05r_dir / "summary.json").resolve()): sha(y05r_dir / "summary.json"),
        str(cstar_path.resolve()): sha(cstar_path),
        **y05r_source_hashes, **y05r_hashes, **old_hashes,
    })
    for meta in parents.values():
        critical[meta["complete_json"]] = meta["complete_sha256"]
        critical[meta["parents_pt"]] = meta["parents_sha256"]

    # Runtime and model identity are stable fields in the frozen protocol; no timestamp/random value.
    props = torch.cuda.get_device_properties(0)
    environment = {
        "gpu_name": props.name,
        "gpu_uuid": str(getattr(props, "uuid", "")),
        "total_memory": int(props.total_memory),
        "torch": str(torch.__version__), "cuda": str(torch.version.cuda),
        "python": sys.version.split()[0], "numpy": str(old_ctx.rt.np.__version__),
        "opencv": str(old_ctx.rt.cv2.__version__),
        "cudnn_benchmark": bool(torch.backends.cudnn.benchmark),
        "matmul_allow_tf32": bool(torch.backends.cuda.matmul.allow_tf32),
        "cudnn_allow_tf32": bool(torch.backends.cudnn.allow_tf32),
    }
    plan = {
        "experiment": "Y12-D", "version": VERSION, "partial_smoke": bool(args.smoke_only),
        "y05r_dir": str(y05r_dir.resolve()), "y05r_signature": y05r_signature,
        "y05r_status": y05r_summary["status"], "source_y05_signature": y05r_protocol["source_y05_signature"],
        "cstar_checkpoint": str(cstar_path.resolve()), "cstar_checkpoint_sha256": sha(cstar_path),
        "cstar_head_sha256": cstar_head_sha,
        "parent_caches": parents, "cases": cases, "settings": frozen_settings(args.smoke_only),
        "environment": environment, "critical_input_sha256": critical,
        "input_hash_policy": "Y05 original preflight revalidates original dataset/source protocol; Y05-R C* checkpoint, own-parent caches and reviewed source/runtime files are SHA-pinned here and rechecked after evaluation.",
        "interpretation_limits": [
            "Three previously used development videos and 27 correlated anchors only; no independent test or statistical generalization claim.",
            "Teacher donor is same-ray radial-conditioned current-frame pixel-encoder evidence, not GT or a theoretical upper bound.",
            "Teacher encoder cost is diagnostic and charged separately; no low-cost deployment claim.",
            "Flow-gradient and warp-validity regions are proxies, not semantic/occlusion ground truth.",
            "Y12-D does not train a new network and cannot grant Y11 or CVPR method pass.",
        ],
    }
    old_ctx.head_state = cstar_state
    old_ctx.out = y05r_dir
    old_ctx.signature = y05r_signature
    old_ctx.y05r_dir = y05r_dir
    old_ctx.y05r_signature = y05r_signature
    old_ctx.cstar_head_sha256 = cstar_head_sha
    old_ctx.y05r_protocol = y05r_protocol
    old_ctx.y05r_summary = y05r_summary
    old_ctx.y05r_parent_metadata = parents
    old_ctx.y05r_checkpoint_sha256 = sha(cstar_path)
    return old_ctx, plan, cases


def verify_critical_inputs(plan):
    for path, digest in plan["critical_input_sha256"].items():
        p = Path(path)
        require(p.is_file() and sha(p) == digest, "Pinned Y12-D input changed during run: " + path)


def archive(ctx, out_dir):
    out_dir = Path(out_dir)
    archive_path = out_dir / "y12d_review.zip"
    tmp = archive_path.with_suffix(".zip.tmp")
    with zipfile.ZipFile(tmp, "w", zipfile.ZIP_DEFLATED, compresslevel=6) as z:
        for p in sorted(out_dir.rglob("*")):
            if not p.is_file() or p == tmp or p == archive_path:
                continue
            rel = p.relative_to(out_dir)
            if any(x in ("cache", "parent_cache", "checkpoints") for x in rel.parts):
                continue
            if p.name.endswith(".tmp") or p.name == "failure.json" or p.name == ".run.lock":
                continue
            if p.suffix in (".csv", ".json", ".jsonl", ".md", ".npz"):
                z.write(p, rel.as_posix())
        for name in INSTALLED:
            z.write(HERE / name, "source/y12d/" + name)
        z.write(ROOT / "run_y12d.sh", "source/y12d/run_y12d.sh")
        for name in ("y05_common.py", "y05_engine.py", "y05_train.py", "y05_eval.py", "gt4a2_y05_future_utility.py"):
            z.write(ROOT / "experiments/p1" / name, "reference/y05/" + name)
        for name in ("gt4a2_y05r.py", "y05r_common.py", "y05r_train.py", "y05r_eval.py", "y05r_identity.json", "y05r_SHA256SUMS"):
            z.write(ROOT / "experiments/p1" / name, "reference/y05r/" + name)
        z.write(ctx.y05r_dir / "protocol.json", "reference/y05r/formal_protocol.json")
        z.write(ctx.y05r_dir / "summary.json", "reference/y05r/formal_summary.json")
        for seq, meta in ctx.y05r_parent_metadata.items():
            z.write(meta["complete_json"], f"reference/y05r/parent_metadata/{seq}_complete.json")
        z.write(ROOT / "experiments/p1/gt4a2_y04a_native_pre_readout_eval.py", "reference/runtime/gt4a2_y04a_native_pre_readout_eval.py")
        for name in ("velodepth.py", "encoder_velo.py", "decoder_velo.py"):
            z.write(ROOT / "velodepth/models" / name, "reference/model/" + name)
    with zipfile.ZipFile(tmp) as z:
        require(z.testzip() is None, "Y12-D review ZIP CRC failed")
    tmp.replace(archive_path)
    return archive_path


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--y05r-dir", default=os.environ.get("Y05R_DIR", "auto"))
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--preflight-only", action="store_true")
    ap.add_argument("--smoke-only", action="store_true")
    ap.add_argument("--resume", action="store_true")
    args = ap.parse_args()
    out_dir = Path(args.out_dir).expanduser().resolve()
    require("gt4a2_y12d_" in str(out_dir), "Use an independent outputs/gt4a2_y12d_<timestamp>/ namespace")
    require(not (args.preflight_only and args.smoke_only), "Choose preflight-only or smoke-only, not both")
    require(not (args.resume and (args.preflight_only or args.smoke_only)), "Resume is only for a formal 27-anchor run")

    if args.resume:
        frozen_path = out_dir / "protocol.json"
        require(frozen_path.is_file(), "--resume requires the formal Y12-D protocol.json")
        frozen = jread(frozen_path)
        require(frozen.get("experiment") == "Y12-D" and not frozen.get("partial_smoke"), "Only a formal Y12-D run can resume")
        args.y05r_dir = frozen["y05r_dir"]
        args.smoke_only = False

    out_dir.mkdir(parents=True, exist_ok=True)
    phase = "preflight"
    started = time.perf_counter()
    with (out_dir / ".run.lock").open("a+") as run_lock:
        try:
            fcntl.flock(run_lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError:
            raise RuntimeError("This Y12-D output directory is already running")
        try:
            ctx, plan, cases = prepare(args, out_dir)
            protocol_path = out_dir / "protocol.json"
            if protocol_path.exists():
                require(args.resume and jread(protocol_path) == plan,
                        "Existing Y12-D protocol differs; use a new output directory or resume the exact formal protocol")
            else:
                require(not args.resume, "Cannot resume without the original frozen protocol")
                jwrite(protocol_path, plan)
            signature = sha(protocol_path)
            ctx.signature = signature
            print(f"[PREFLIGHT PASS] {VERSION}; anchors={len(cases)}; parent=C_star own S8; branches=3; H=4", flush=True)
            print(f"[Y05-R] {ctx.y05r_dir}; signature={ctx.y05r_protocol and sha(ctx.y05r_dir / 'protocol.json')}", flush=True)
            print(f"[PROTOCOL] {protocol_path}; signature={signature}", flush=True)
            if args.preflight_only:
                print("[PREFLIGHT ONLY] no anchor forward or teacher donor evaluation performed", flush=True)
                return 0

            uuid = plan["environment"].get("gpu_uuid") or plan["environment"].get("gpu_name") or "unknown-gpu"
            lock_path = Path("/tmp") / ("svrdepth_y12d_" + hashlib.sha256(str(uuid).encode()).hexdigest()[:16] + ".lock")
            with lock_path.open("a+") as gpu_lock:
                print("[GPU QUEUE] waiting for exclusive GPU access", flush=True)
                fcntl.flock(gpu_lock, fcntl.LOCK_EX)
                ctx.rt.torch.set_num_threads(4)
                phase = "real-CUDA-evaluation"
                from y05_engine import Engine
                engine = Engine(ctx, SEQS[0])
                for parameter in engine.model.parameters():
                    parameter.requires_grad_(False)
                try:
                    from y12d_eval import evaluate_cases
                    evaluate_cases(ctx, engine, cases, out_dir, signature,
                                   resume=args.resume, partial_smoke=args.smoke_only)
                finally:
                    engine.close()
                verify_critical_inputs(plan)
                if args.smoke_only:
                    print("[SMOKE PASS] Real CUDA 3-anchor/3-sequence Y12-D smoke completed; not a recovery-space result.", flush=True)
                    return 0
                phase = "archive"
                summary_path = out_dir / "summary.json"
                summary = jread(summary_path)
                summary["review_package"] = str((out_dir / "y12d_review.zip").resolve())
                jwrite(summary_path, summary)
                result = archive(ctx, out_dir)
                print("[VERIFIED]", result.resolve(), flush=True)
                print("[SUMMARY]", summary_path.resolve(), flush=True)
            with (out_dir / "invocations.jsonl").open("a", encoding="utf-8") as f:
                f.write(json.dumps({"completed": True, "resume": args.resume,
                                    "wall_sec": time.perf_counter() - started, "unix_time": time.time()}) + "\n")
            return 0
        except BaseException as exc:
            jwrite(out_dir / "failure.json", {"phase": phase, "error": str(exc), "traceback": traceback.format_exc()})
            with (out_dir / "invocations.jsonl").open("a", encoding="utf-8") as f:
                f.write(json.dumps({"completed": False, "resume": args.resume,
                                    "phase": phase, "wall_sec": time.perf_counter() - started,
                                    "unix_time": time.time()}) + "\n")
            raise


if __name__ == "__main__":
    raise SystemExit(main())
